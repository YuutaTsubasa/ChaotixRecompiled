// One line of header, the stages that were asked for, then one pad word per
// emulated frame: enough for chaotix_headless --replay-input to play the
// session back exactly.
void write_recording(const App& app, const std::string& path, int result_frames = -1) {
    FILE* f = std::fopen(path.c_str(), "w");
    if (!f) { LOGW("app", "could not write %s", path.c_str()); return; }
    std::fprintf(f, "chaotix-input 1 frames=%zu\n", app.recorded.size());
    // What this session produced, so a replay can say at once whether it
    // reproduced the session or drifted off somewhere else.
    if (result_frames >= 0) std::fprintf(f, "result %d\n", result_frames);
    for (const auto& e : app.recorded_stages)
        std::fprintf(f, "stage %llu %u %u %u %u %u %d %d %d %d\n", (unsigned long long)e.frame,
                     e.request.place, e.request.level, e.request.attime, e.request.player,
                     e.request.combi, int(e.request.two_players), e.wide, e.wide_bottom,
                     int(e.six_button));
    for (const auto& e : app.recorded_lobby)
        std::fprintf(f, "lobby %llu %d %d\n", (unsigned long long)e.frame, e.partner, e.time);
    for (const auto& e : app.recorded_tether)
        std::fprintf(f, "tether %llu %d %d\n", (unsigned long long)e.frame, e.strength, e.partner);
    for (uint32_t v : app.recorded) std::fprintf(f, "%X\n", v);
    std::fclose(f);
    LOGI("app", "session recorded to %s (%zu frames)", path.c_str(), app.recorded.size());
}

void capture_output(App& app) {
    SDL_Surface* s = SDL_RenderReadPixels(app.renderer, nullptr);
    if (!s) { LOGW("app", "SDL_RenderReadPixels: %s", SDL_GetError()); return; }
    SDL_Surface* c = SDL_ConvertSurface(s, SDL_PIXELFORMAT_XRGB8888);
    SDL_DestroySurface(s);
    if (!c) return;
    write_png(app.autotest_shot, static_cast<const uint32_t*>(c->pixels), c->w, c->h, c->pitch / 4);
    LOGI("app", "autotest: captured %dx%d output to %s", c->w, c->h, app.autotest_shot.c_str());
    SDL_DestroySurface(c);
}

// Places a user's ROM is likely to be, for the first-run setup to offer.
std::vector<std::string> rom_search_dirs(const App& app) {
    std::vector<std::filesystem::path> dirs = {"__ROM__", "rom", "."};
    if (const char* base = SDL_GetBasePath()) {
        dirs.push_back(std::filesystem::path(base) / "__ROM__");
        dirs.push_back(std::filesystem::path(base) / "rom");
        dirs.push_back(std::filesystem::path(base));
    }
    dirs.push_back(std::filesystem::path(app.store.root()) / "rom");
    // Desktop: the usual download/document folders. Mobile: the app's own
    // documents folder, which is what file managers expose.
#ifdef SDL_PLATFORM_IOS
    // An iOS app's own Downloads and Desktop are folders nobody can reach
    // (SDL would create them); Documents is the one the Files app shows.
    const SDL_Folder folders[] = {SDL_FOLDER_DOCUMENTS};
#else
    const SDL_Folder folders[] = {SDL_FOLDER_DOWNLOADS, SDL_FOLDER_DOCUMENTS, SDL_FOLDER_DESKTOP};
#endif
    for (SDL_Folder f : folders)
        if (const char* p = SDL_GetUserFolder(f)) {
            dirs.push_back(std::filesystem::path(p));
            dirs.push_back(std::filesystem::path(p) / "Chaotix");
        }
#if defined(SDL_PLATFORM_ANDROID)
    if (const char* ext = SDL_GetAndroidExternalStoragePath()) {
        dirs.push_back(std::filesystem::path(ext));
        dirs.push_back(std::filesystem::path(ext) / "rom");
    }
#endif
    std::vector<std::string> out;
    for (const auto& d : dirs) out.push_back(d.string());
    return out;
}

// Options that take a separate value, so a ROM path on the command line is
// not confused with one of them.
bool option_takes_value(const std::string& a) {
    static const char* with_value[] = {"--aspect", "--autotest", "--autotest-shot", "--window-size",
                                       "--press", "--user-dir", "--install", "--menu", "--keys", "--shots", "--hold", "--record-input", "--mods-dir", "--stage",
                                       "--rewind-hold", "--netplay-host", "--netplay-join", "--menu-size"};
    for (const char* o : with_value)
        if (a == o) return true;
    return false;
}

// A ROM given on the command line wins over everything else.
std::string rom_from_args(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        if (!a.empty() && a[0] == '-') {
            if (option_takes_value(a)) ++i;
            continue;
        }
        if (a.size() > 4) return a;
    }
    return "";
}

void apply_window_mode(App& app) {
    switch (app.cfg.window_mode) {
    case WindowMode::Windowed:
        SDL_SetWindowFullscreen(app.window, false);
        SDL_SetWindowBordered(app.window, true);
        break;
    case WindowMode::Borderless:
        SDL_SetWindowFullscreenMode(app.window, nullptr);  // desktop-sized, no mode change
        SDL_SetWindowFullscreen(app.window, true);
        break;
    case WindowMode::Fullscreen: {
        SDL_DisplayID disp = SDL_GetDisplayForWindow(app.window);
        const SDL_DisplayMode* dm = SDL_GetDesktopDisplayMode(disp);
        SDL_DisplayMode closest;
        if (dm && SDL_GetClosestFullscreenDisplayMode(disp, dm->w, dm->h, dm->refresh_rate, true, &closest))
            SDL_SetWindowFullscreenMode(app.window, &closest);
        SDL_SetWindowFullscreen(app.window, true);
        break;
    }
    }
}

uint16_t keyboard_buttons(const App& app, int player) {
    const bool* ks = SDL_GetKeyboardState(nullptr);
    const auto& binds = player == 0 ? app.cfg.keys : app.cfg.keys2;
    uint16_t out = 0;
    for (const auto& [name, keyname] : binds) {
        SDL_Scancode sc = SDL_GetScancodeFromName(keyname.c_str());
        if (sc != SDL_SCANCODE_UNKNOWN && ks[sc]) out |= pad_button_from_name(name.c_str());
    }
    return out;
}

// A binding that does not name a real key does nothing, silently, which is
// impossible to tell from a key that simply is not pressed. Say so once.
void warn_about_dead_bindings(const App& app) {
    for (int p = 0; p < 2; ++p) {
        for (const auto& [name, keyname] : (p == 0 ? app.cfg.keys : app.cfg.keys2)) {
            if (SDL_GetScancodeFromName(keyname.c_str()) == SDL_SCANCODE_UNKNOWN)
                LOGW("input", "player %d: \"%s\" is not a key name, so %s is unbound",
                     p + 1, keyname.c_str(), name.c_str());
        }
    }
}

// The Mega Drive pad the game sees, from whatever the player bound to it.
// Defaults are in Config::set_defaults; anything here can be rebound.
uint16_t gamepad_buttons(SDL_Gamepad* g, const std::map<std::string, std::string>& binds) {
    uint16_t out = 0;
    for (const auto& [name, sdl_name] : binds) {
        const SDL_GamepadButton b = SDL_GetGamepadButtonFromString(sdl_name.c_str());
        if (b != SDL_GAMEPAD_BUTTON_INVALID && SDL_GetGamepadButton(g, b))
            out |= pad_button_from_name(name.c_str());
    }
    // The sticks always steer, whatever the d-pad is bound to.
    const int dead = 12000;
    const int lx = SDL_GetGamepadAxis(g, SDL_GAMEPAD_AXIS_LEFTX);
    const int ly = SDL_GetGamepadAxis(g, SDL_GAMEPAD_AXIS_LEFTY);
    if (lx < -dead) out |= PAD_LEFT;
    if (lx > dead) out |= PAD_RIGHT;
    if (ly < -dead) out |= PAD_UP;
    if (ly > dead) out |= PAD_DOWN;
    return out;
}

// Which physical device drives a player: "auto", "keyboard", "padN", "none".
uint16_t device_buttons(const App& app, int player) {
    const std::string& dev = app.cfg.device[player];
    const std::string& other = app.cfg.device[1 - player];
    if (dev == "none") return 0;
    if (dev.rfind("pad", 0) == 0) {
        const size_t i = size_t(std::atoi(dev.c_str() + 3)) - 1;  // pad1 is the first
        const auto& binds = player == 0 ? app.cfg.pads : app.cfg.pads2;
        return i < app.pads.size() ? gamepad_buttons(app.pads[i], binds) : uint16_t(0);
    }
    uint16_t out = keyboard_buttons(app, player);
    // "auto" also answers to every gamepad, which is what someone who has
    // never opened the controls page expects. A pad the other player has
    // claimed is left alone, so the two do not drive each other.
    if (dev == "auto") {
        const auto& binds = player == 0 ? app.cfg.pads : app.cfg.pads2;
        for (size_t i = 0; i < app.pads.size(); ++i) {
            if (other == "pad" + std::to_string(i + 1)) continue;
            out |= gamepad_buttons(app.pads[i], binds);
        }
    }
    return out;
}

