// Save states (issue #40). Files in <user data>/States, one per slot and ROM.
// ---------------------------------------------------------------------------
std::string state_path(const App& app, int slot) {
    return app.store.root() + "States/chaotix_" + app.m->rom.sha1.substr(0, 8) + "_" + std::to_string(slot) + ".state";
}

// Why states and rewind cannot be used now, or empty when they can. Never in
// a TIME ATTACK run: a record is set in one go, at the game's own speed.
std::string states_locked(const App& app) {
    if (app.net.on) return "NOT IN NETPLAY";
    if (app.ta.running) return "NOT IN TIME ATTACK";
    if (!app.handed_over) return "START THE GAME FIRST";
    if (app.stage_kick >= 0) return "THE STAGE IS STARTING";
    return "";
}

void notice(App& app, const std::string& caption, const std::string& title, const std::string& note = "") {
    // One at a time: a row of SAVED from pressing it repeatedly is noise.
    app.toasts.erase(std::remove_if(app.toasts.begin(), app.toasts.end(),
                                    [&](const App::Toast& t) { return t.caption == caption; }),
                     app.toasts.end());
    app.toasts.push_back({title, note, SDL_GetTicks() + 2500, caption});
}

void save_state(App& app, int slot) {
    const std::string why = states_locked(app);
    if (!why.empty()) { notice(app, "SAVE STATE", why); return; }
    const std::vector<uint8_t> bytes = savestate::save(*app.m, app.music.save_position(), int64_t(std::time(nullptr)));
    std::error_code ec;
    std::filesystem::create_directories(std::filesystem::u8path(app.store.root() + "States"), ec);
    const std::string path = state_path(app, slot);
    if (!savestate::write_file(path, bytes)) {
        LOGW("state", "cannot write %s", path.c_str());
        notice(app, "SAVE STATE", "STATE " + std::to_string(slot) + " NOT SAVED", "The file could not be written.");
        return;
    }
    LOGI("state", "slot %d saved at frame %llu to %s (%zu bytes)", slot, (unsigned long long)app.m->frame_count,
         path.c_str(), bytes.size());
    notice(app, "SAVE STATE", "STATE " + std::to_string(slot) + " SAVED");
}

// After the machine jumped in time (a state loaded): what the host keeps
// about the moment before no longer applies.
void after_time_jump(App& app) {
    app.inject_start = 0;
    app.m->audio_out.clear();
    if (app.audio) SDL_ClearAudioStream(app.audio);
    app.achievements.forget_previous();
}

void load_state(App& app, int slot) {
    const std::string why = states_locked(app);
    if (!why.empty()) { notice(app, "LOAD STATE", why); return; }
    std::vector<uint8_t> bytes;
    const std::string name = "STATE " + std::to_string(slot);
    if (!savestate::read_file(state_path(app, slot), bytes)) { notice(app, "LOAD STATE", name + " IS EMPTY"); return; }
    std::string err;
    std::vector<uint8_t> host;
    if (!savestate::load(*app.m, bytes, &err, &host)) {
        LOGW("state", "slot %d: %s", slot, err.c_str());
        // The menu's font has capitals only.
        for (char& ch : err) ch = char(std::toupper(static_cast<unsigned char>(ch)));
        notice(app, "LOAD STATE", name + " NOT LOADED", err);
        return;
    }
    app.music.load_position(host);
    // A state saved in story mode (a DATA slot in FFE01C) is the game going
    // on as it was: a LEVEL SELECT session does not send it back to the
    // page. One saved in practice (NO SAVE, 0xFFFF) keeps the session.
    if (app.ls.running && (app.m->wram[0xE01C] << 8 | app.m->wram[0xE01D]) != 0xFFFF) app.ls.cancel();
    app.rewind.clear();
    app.rewind_music.clear();
    after_time_jump(app);
    LOGI("state", "slot %d loaded (frame %llu)", slot, (unsigned long long)app.m->frame_count);
    notice(app, "LOAD STATE", name + " LOADED");
}

// What a slot holds, for the menu.
std::string state_info(const App& app, int slot) {
    std::vector<uint8_t> bytes;
    if (!savestate::read_file(state_path(app, slot), bytes)) return "EMPTY";
    savestate::Info info;
    std::string err;
    if (!savestate::read_info(bytes, info, &err)) return "UNREADABLE";
    if (info.game_version != savestate::game_version()) return "FROM VERSION " + info.game_version;
    if (!info.saved_unix) return "SAVED";
    const std::time_t t = std::time_t(info.saved_unix);
    char buf[32];
    if (const std::tm* tm = std::localtime(&t)) std::strftime(buf, sizeof buf, "SAVED %Y-%m-%d %H:%M", tm);
    else std::snprintf(buf, sizeof buf, "SAVED");
    return buf;
}

// One step back through the rewind buffer, and a frame run from there for a
// picture, with the pad let go and the sound dropped. The game then carries
// on from that frame when rewind is let go.
void rewind_step(App& app) {
    // Nothing to go back to (just after a load, say): the game holds still
    // rather than running on with the pad let go.
    if (!app.rewind.snapshots()) return;
    app.rewind.step_back(*app.m);
    auto it = app.rewind_music.find(app.m->frame_count);
    if (it != app.rewind_music.end()) app.music.load_position(it->second);
    app.achievements.forget_previous();
    app.m->input.pad[0] = app.m->input.pad[1] = 0;
    app.m->run_frame();
    app.m->audio_out.clear();
    app.m->music_events.clear();
}

// The music player's machine (issue #48), made when its page opens: by the
// main loop, or by the page's first request if that comes in the same pass.
void open_jukebox(App& app) {
    if (app.jukebox_open || app.net.on) return;  // netplay: the game cannot be held
    app.jukebox.begin(app.m->rom, &app.music, app.recompiled);
    app.jukebox.set_tracks(jukebox::track_list(app.m->rom));
    app.jukebox_open = true;
    app.m->audio_out.clear();
    if (app.audio) SDL_ClearAudioStream(app.audio);
    LOGI("music", "music player opened (%s); the game is held", app.jukebox.recompiled() ? "recompiled" : "interpreted");
}

void rewind_push(App& app) {
    app.rewind.set_budget(kRewindBudget);
    app.rewind.set_max_snapshots(kRewindMaxSnapshots);
    app.rewind.push(*app.m);
    app.rewind_music[app.m->frame_count] = app.music.save_position();
    const uint64_t oldest = app.rewind.oldest_frame();
    app.rewind_music.erase(app.rewind_music.begin(), app.rewind_music.lower_bound(oldest));
}

// A stage the front end asked for is taken at the game's mode dispatcher, and
// the title screen only gets back there once it is done with itself: one press
// of Start gets past its animation, another leaves it. So Start is tapped
// until the request is taken -- without this the stage waits out the whole
// title screen, about eight seconds of PUSH START.
uint16_t stage_kick_button(App& app) {
    if (app.stage_kick < 0) return 0;
    if (!app.m->stage_pending) {
        app.stage_kick = -1;   // taken: stop at once, or Start would pause the level
        return 0;
    }
    if (app.stage_kick > 900) {
        // Some scene the request cannot interrupt. Leave it waiting rather
        // than hold Start down on the game for ever.
        LOGW("stage", "the game has not come back to its mode dispatcher; the stage is still waiting");
        app.stage_kick = -1;
        return 0;
    }
    // Taps, not a hold: the title screen wants separate presses.
    const bool down = app.stage_kick % 24 < 6;
    ++app.stage_kick;
    return down ? uint16_t(PAD_START) : uint16_t(0);
}

// Watches a time attack run; called once per emulated frame. The game just
// moves the player on when a run ends, so the frontend takes the time and puts
// itself back instead, which is where the player came from.
// Issue #20: the cheats switched on, set before each frame.
void apply_cheats(App& app) {
    std::vector<cheats::Write> writes;
    for (const auto& c : cheats::builtin())
        if (app.cfg.cheats.count(c.key)) writes.insert(writes.end(), c.writes.begin(), c.writes.end());
    if (!app.cfg.cheat_codes.empty()) cheats::parse_codes(app.cfg.cheat_codes, writes);
    app.cheating = !writes.empty();
    if (app.cheating && app.ta.running) app.ta_cheated = true;
    cheats::apply(*app.m, writes);
}

// Issue #44: the lobby shortcuts, set before each frame like the cheats. A
// TIME ATTACK run picks its own characters and time, so they are off for it,
// as they are for LEVEL SELECT (issue #51), which does too.
void apply_lobby_shortcuts(App& app) {
    const bool on = app.cfg.lobby_shortcuts && !app.ta.running && !app.ls.running;
    const int partner = on ? app.cfg.lobby_partner : -1;
    const int time = on ? app.cfg.lobby_time : -1;
    if (partner == app.m->lobby_partner && time == app.m->lobby_time) return;
    app.m->lobby_partner = partner;
    app.m->lobby_time = time;
    app.recorded_lobby.push_back({app.m->frame_count, partner, time});
}

// Issue #43: the ring tether options, set before each frame like the lobby
// shortcuts. Off for TIME ATTACK runs, so their times compare like with like.
// Issue #55: PARTNER NONE, picked on LEVEL SELECT's page for its session or
// as the lobby shortcut (put in the machine just before, by
// apply_lobby_shortcuts, which leaves it out for TIME ATTACK and LEVEL
// SELECT), plays as PARTNER SOLO whatever GAMEPLAY says; once the session is
// over, or the shortcut off, GAMEPLAY's own setting is back, since this is
// worked out afresh every frame and the setting itself is never changed.
void apply_tether(App& app) {
    const bool on = !app.ta.running;
    const bool picked_none = app.ls.solo_now() || app.m->lobby_partner == lobby::kPartnerNone;
    const int strength = on ? std::clamp(app.cfg.tether_strength, 0, tether::kStrengthCount - 1) : 0;
    const int partner = int(tether::partner_in_force(app.cfg.tether_partner, !on, picked_none));
    if (strength == app.m->tether_strength && partner == app.m->tether_partner) return;
    app.m->tether_strength = uint8_t(strength);
    app.m->tether_partner = uint8_t(partner);
    app.recorded_tether.push_back({app.m->frame_count, strength, partner});
}

// Settings and the cartridge save, written now. Android ends an app without
// a quit event when it is swiped away, so waiting for the exit lost every
// setting there (issue #26): this runs whenever the menu closes and whenever
// the app goes to the background.
// A netplay client plays the host's save: its own is not written over.
bool sram_is_ours(const App& app) { return !(app.net.on && !app.net.session.is_host()); }

void save_now(App& app) {
    if (app.autotest_frames) return;  // autotests are hermetic
    if (app.m->sram_dirty && sram_is_ours(app)) app.store.store_sram(*app.m);
    if (!app.cfg.save(app.store.config_file()))
        LOGW("app", "cannot save settings to %s", app.store.config_file().c_str());
}

