// Where mods are read from: the user data folder. On Android that is the
// app's private storage, so there it is ChaotixRecompiled/Mods on shared
// storage once the app may use it (issue #29; OPTIONS > EXTRAS > MODS > MODS FOLDER asks),
// and until then the app's own folder there (Android/data/<app>/files), which
// only a computer can reach on Android 11 and later.
std::string mods_root(const App& app) {
    if (!app.mods_dir.empty()) {
        const char last = app.mods_dir.back();
        return last == '/' || last == '\\' ? app.mods_dir : app.mods_dir + "/";
    }
#ifdef SDL_PLATFORM_ANDROID
    if (android_shared_storage()) {
        const std::string shared = android_shared_mods_dir();
        if (!shared.empty()) return shared;
    }
    if (const char* ext = SDL_GetAndroidExternalStoragePath()) return std::string(ext) + "/Mods/";
#endif
    return app.store.root() + "Mods/";
}

// Touch control images (issue #25): "<name>.bmp" and "<name>_pressed.bmp" in
// dir, names dpad, a, b, c, x, y, z, start; "button" stands in for any face
// button without its own. BMP because SDL reads it everywhere without another
// library; 32-bit BMP keeps transparency. `dir` is the Mods folder's own
// Touch folder (the README goes there); `dirs` are the enabled packs' Touch
// folders, lowest priority first (issue #42), each image taken from the
// highest one that has it.
void load_touch_skin(App& app, const std::string& dir, const std::vector<std::string>& dirs) {
    std::error_code ec;
    std::filesystem::create_directories(std::filesystem::u8path(dir), ec);
    const std::string readme = dir + "/README.txt";
    if (!std::filesystem::exists(std::filesystem::u8path(readme), ec)) {
        if (FILE* f = std::fopen(readme.c_str(), "w")) {
            std::fputs("Touch control images. Put BMP files here (32-bit keeps transparency):\n"
                       "  dpad.bmp a.bmp b.bmp c.bmp x.bmp y.bmp z.bmp start.bmp\n"
                       "  stick.bmp and knob.bmp for the joystick (OPTIONS > INPUT > TOUCH STICK).\n"
                       "  ff.bmp for fast-forward (OPTIONS > INPUT > TOUCH FAST FORWARD).\n"
                       "  rew.bmp for rewind (OPTIONS > INPUT > TOUCH REWIND).\n"
                       "  button.bmp is used for any face button without its own file.\n"
                       "  <name>_pressed.bmp is drawn while that button is held.\n"
                       "Each image is stretched to the button's square; a missing one is drawn as before.\n",
                       f);
            std::fclose(f);
        }
    }
    int loaded = 0;
    for (const char* name : {"dpad", "stick", "knob", "a", "b", "c", "x", "y", "z", "start", "ff", "rew", "button"}) {
        for (int pressed = 0; pressed < 2; ++pressed) {
            SDL_Surface* s = nullptr;
            for (auto it = dirs.rbegin(); it != dirs.rend() && !s; ++it) {
                const std::string path = *it + "/" + name + (pressed ? "_pressed" : "") + ".bmp";
                s = SDL_LoadBMP(path.c_str());
            }
            if (!s) continue;
            if (SDL_Texture* t = SDL_CreateTextureFromSurface(app.renderer, s)) {
                SDL_SetTextureBlendMode(t, SDL_BLENDMODE_BLEND);
                app.touch_skin[name][size_t(pressed)] = t;
                ++loaded;
            }
            SDL_DestroySurface(s);
        }
    }
    if (loaded) LOGI("touch", "%d touch control image(s) from %zu folder(s)", loaded, dirs.size());
}

// Mod packs (issue #42): reads the Mods folder again and puts what is there
// in the player's order. Packs new since the last time join the end of the
// list, and the order in the settings is brought up to date.
void scan_packs(App& app) {
    std::vector<std::string> messages;
    app.packs = mod_packs::arrange(mod_packs::discover(mods_root(app), savestate::game_version(), &messages),
                                   app.cfg.mod_order);
    for (const auto& msg : messages) LOGW("mods", "%s", msg.c_str());
    mod_packs::remember(app.cfg.mod_order, app.packs);
    for (const auto& p : app.packs)
        LOGI("mods", "%s %s%s%s (%s)", p.enabled ? "[on] " : "[off]", p.title().c_str(),
             p.info.version.empty() ? "" : " ", p.info.version.c_str(), p.loose ? "Mods/" : p.id.c_str());
}

// The enabled packs' folders of one kind, lowest priority first.
std::vector<std::string> mod_folders(const App& app, const char* kind) {
    return mod_packs::folders(app.packs, kind);
}

// Puts the 32X sprite recorder on the machine when it is needed (a sprite
// pack, or the dump on) and takes it off when not: recording costs a little
// every frame. Called every frame, as a copy of the machine put back (the
// title snapshot) may carry another one.
void update_sprite_recorder(App& app) {
    const bool want = app.sprite_pack || app.cfg.dump_graphics;
    if (!want) app.sprites.reset();
    else if (!app.sprites) app.sprites = std::make_shared<SpriteRecorder>();
    if (app.sprites) {
        app.sprites->set_pack(app.sprite_pack);
        app.sprites->dumping = app.cfg.dump_graphics;
    }
    if (app.m->sprites != app.sprites) app.m->sprites = app.sprites;
}

// The character cards' sprites are made again after the mods change.
void drop_portraits(App& app) {
    for (auto& entry : app.portraits)
        if (entry.second.texture) SDL_DestroyTexture(entry.second.texture);
    app.portraits.clear();
}

// Graphics replacements (issue #35), in Mods/Textures: Mega Drive tiles as
// md_<hash>.png and 32X sprites as 32x_<bank>_<frame>.png or 32x_<hash>.png.
// With DUMP GRAPHICS on, each one drawn is also written to Mods/Textures/Dump
// once.
void load_tiles(App& app) {
    const std::string dir = mods_root(app) + "Textures";
    std::error_code ec;
    std::filesystem::create_directories(std::filesystem::u8path(dir), ec);
    const std::string readme = dir + "/README.txt";
    // Written when missing, and over the text of older versions: the first
    // knew only the tiles, the next not the text patterns, the next not the
    // sprite text.
    bool write_readme = !std::filesystem::exists(std::filesystem::u8path(readme), ec);
    if (!write_readme) {
        if (FILE* f = std::fopen(readme.c_str(), "r")) {
            char first[64] = {};
            if (std::fgets(first, sizeof first, f)) {
                write_readme = std::strncmp(first, "Mega Drive tile replacements:", 29) == 0;
                if (std::strncmp(first, "Graphics replacements.", 22) == 0) {
                    bool knows_text = false;
                    char line[256];
                    while (!knows_text && std::fgets(line, sizeof line, f)) knows_text = std::strstr(line, "mdsprite_") != nullptr;
                    write_readme = !knows_text;
                }
            }
            std::fclose(f);
        }
    }
    if (write_readme) {
        if (FILE* f = std::fopen(readme.c_str(), "w")) {
            std::fputs("Graphics replacements. Turn on OPTIONS > EXTRAS > DUMP GRAPHICS and play: each\n"
                       "graphic the game draws is saved once to the Dump folder. Edit one in an editor\n"
                       "that keeps it palette-indexed (the colours are the game's palette, index 0 is\n"
                       "transparent) and put it in this folder under the same name. It is drawn instead\n"
                       "of the original wherever the game uses it.\n"
                       "\n"
                       "md_<hash>.png: Mega Drive tiles (backgrounds, level art). Keep them 8x8.\n"
                       "mdtext_<name>.txt with mdtext_<name>.png: Mega Drive text by tile sequence\n"
                       "(menus written with letter tiles). The dump lists the runs of tiles on screen\n"
                       "in Dump/Text, with a numbered picture; copy a run's \"plane\" and \"row\" lines\n"
                       "into the .txt and draw the .png, 8 pixels high per row (docs/TEXTURE_MODS.md).\n"
                       "mdsprite_<name>.txt with mdsprite_<name>.png: the same for text drawn with\n"
                       "Mega Drive sprites (the menu banners' letters): Dump/Text/sprites_<n>.txt\n"
                       "lists the sprites on screen in groups; copy a group's \"sprite\" lines.\n"
                       "32x_<bank>_<frame>.png, 32x_<hash>.png: 32X sprites (characters, the HUD,\n"
                       "objects, the title). The image's top-left corner stays where the original's\n"
                       "was; another size is drawn at its own size from there. The colour offsets the\n"
                       "game gives the characters still apply, so keep to the indices the dump uses.\n"
                       "\n"
                       "32x_<bank>.png with 32x_<bank>.txt: every frame of a bank in one sheet.\n"
                       "OPTIONS > EXTRAS > EXPORT SPRITES writes the characters' sheets to the Sheets\n"
                       "folder; copy a sheet and its .txt here to use it. A frame's own file wins.\n"
                       "\n"
                       "A mod pack keeps the same files in its own Textures folder, Mods/<pack>/\n"
                       "Textures (see Mods/README.txt). Files here win over every pack's.\n",
                       f);
            std::fclose(f);
        }
    }
    // Every enabled pack's Textures folder, the loose one (this one) last:
    // a later folder's graphic replaces an earlier one's (issue #42).
    const std::vector<std::string> dirs = mod_folders(app, mod_packs::kTextures);
    auto tiles = std::make_shared<TileReplacer>();
    std::vector<std::string> messages;
    const int n = load_tile_packs(*tiles, dirs, &messages);
    for (const auto& m : messages) LOGW("tiles", "%s", m.c_str());
    if (n) LOGI("tiles", "%d tile replacement(s) from %zu folder(s)", n, dirs.size());
    messages.clear();
    const int tn = load_text_packs(*tiles, dirs, &messages);
    for (const auto& m : messages) LOGW("text", "%s", m.c_str());
    if (tn) LOGI("text", "%d text pattern(s) from %zu folder(s)", tn, dirs.size());
    tiles->dumping = app.cfg.dump_graphics;
    app.tiles_dir = dir;
    app.tiles = tiles;
    app.m->vdp.tiles = tiles;

    auto pack = std::make_shared<SpritePack>();
    messages.clear();
    const int sn = load_sprite_packs(*pack, dirs, &messages);
    for (const auto& m : messages) LOGW("sprites", "%s", m.c_str());
    if (sn) LOGI("sprites", "%d sprite replacement(s) from %zu folder(s)", sn, dirs.size());
    app.sprite_pack = sn ? pack : nullptr;
    update_sprite_recorder(app);
    drop_portraits(app);
}

// The character cards' sprites (issue #53, frontend/portrait.h): a
// character standing, from the ROM's bank with the sprite mods and the
// character's colours applied; made when first asked for. Null for a
// character without graphics.
SDL_Texture* character_sprite(App& app, int who, float* w, float* h) {
    if (!app.m || !app.renderer) return nullptr;
    auto it = app.portraits.find(who);
    if (it == app.portraits.end()) {
        App::Preview pv;
        const CharacterMod* mod = nullptr;
        for (const CharacterMod& c : app.portrait_mods)
            if (c.id == who) mod = &c;
        Portrait portrait;
        std::string why;
        if (character_portrait(app.m->rom, who, app.sprite_pack.get(), mod, portrait, &why)) {
            pv.texture = SDL_CreateTexture(app.renderer, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STATIC,
                                           portrait.width, portrait.height);
            if (pv.texture) {
                SDL_UpdateTexture(pv.texture, nullptr, portrait.argb.data(), portrait.width * 4);
                SDL_SetTextureBlendMode(pv.texture, SDL_BLENDMODE_BLEND);
                SDL_SetTextureScaleMode(pv.texture, SDL_SCALEMODE_NEAREST);
                pv.w = float(portrait.width);
                pv.h = float(portrait.height);
            }
        } else {
            LOGI("menu", "no card sprite for character %d: %s", who, why.c_str());
        }
        it = app.portraits.emplace(who, pv).first;
    }
    *w = it->second.w;
    *h = it->second.h;
    return it->second.texture;
}

// Character mods (docs/CHARACTER_MODS.md): Mods/Characters/<name>.ini, read
// both for their colours (load_mods) and their stats (apply_rom_patches).
std::vector<CharacterMod> read_character_mods(App& app) {
    const std::string dir = mods_root(app) + "Characters";
    std::error_code ec;
    std::filesystem::create_directories(std::filesystem::u8path(dir), ec);
    const std::string readme = dir + "/README.txt";
    if (!std::filesystem::exists(std::filesystem::u8path(readme), ec)) {
        if (FILE* f = std::fopen(readme.c_str(), "w")) {
            std::fputs("Character mods. One file per character, named mighty.ini, knuckles.ini,\n"
                       "charmy.ini, vector.ini, bomb.ini, heavy.ini or espio.ini, with any of:\n"
                       "\n"
                       "[Palette]      the character's 18 colours, by pixel value (1 to 18):\n"
                       "1 = #RRGGBB    rounded to the 32X's 32 levels per component, or a 32X\n"
                       "               colour as stored (0x0000-0x7FFF, blue-green-red, 5 bits each).\n"
                       "[Cycle]        Espio only: his 16 shimmer sets, five colours each\n"
                       "0 = #RRGGBB #RRGGBB #RRGGBB #RRGGBB #RRGGBB   (for pixels 2 to 6)\n"
                       "[Stats]        how the character moves, in the game's own units:\n"
                       "acceleration = 0x0C   speed_cap, deceleration, gravity, jump, jump_release,\n"
                       "               roll_friction, spin_dash_min/max/step, glide_speed, glide_fall_speed,\n"
                       "               air_dash_speed, ... (see docs/CHARACTER_MODS.md)\n"
                       "\n"
                       "Colours change only the picture. Stats change how the game plays and take\n"
                       "effect the next time the game is started. Lines starting with ; are comments.\n"
                       "New looks for the sprites themselves go in Mods/Textures.\n",
                       f);
            std::fclose(f);
        }
    }
    std::vector<std::string> messages;
    // A character's file from a higher pack replaces a lower one's (issue #42).
    std::vector<CharacterMod> mods = load_character_mods(mod_folders(app, mod_packs::kCharacters), &messages);
    for (const auto& msg : messages) LOGW("characters", "%s", msg.c_str());
    return mods;
}

// Music, touch images, graphics and character colours from the Mods folder
// and the enabled mod packs; again when that folder has changed (Android:
// shared storage access granted while the app was away) or, with `force`,
// when the packs have (OPTIONS > EXTRAS > MODS). None of these change the
// game itself, so they apply at once; patches and character stats wait for
// the next start (apply_rom_patches).
void load_mods(App& app, bool force = false) {
    const std::string mods = mods_root(app);
    if (mods == app.mods_loaded_from && !force) return;
    app.mods_loaded_from = mods;
    scan_packs(app);
    for (auto& entry : app.touch_skin)
        for (SDL_Texture* tex : entry.second) if (tex) SDL_DestroyTexture(tex);
    app.touch_skin.clear();
    for (auto& entry : app.mod_previews)
        if (entry.second.texture) SDL_DestroyTexture(entry.second.texture);
    app.mod_previews.clear();
    // The piece playing from a file carries on if it is still there.
    const std::vector<uint8_t> music_position = app.music.save_position();
    app.music = audio::MusicMods{};
    // Created so they are easy to find; empty, they change nothing.
    const std::string music_dir = mods + "Music";
    std::error_code ec;
    std::filesystem::create_directories(std::filesystem::u8path(music_dir), ec);
    const std::vector<std::string> music_dirs = mod_folders(app, mod_packs::kMusic);
    int music_files = 0;
    for (const auto& dir : music_dirs) music_files = app.music.scan(dir);
    if (music_files) LOGI("music", "%d piece(s) of music replaced from %zu folder(s)", music_files, music_dirs.size());
    app.music.attach(*app.m);
    if (force) app.music.load_position(music_position);
    load_touch_skin(app, mods + "Touch", mod_folders(app, mod_packs::kTouch));
    load_tiles(app);
    // The characters' colours, from the ROM as it runs (patched or not).
    app.portrait_mods = read_character_mods(app);
    drop_portraits(app);
    auto palettes = std::make_shared<CharacterPalettes>(app.m->rom, app.portrait_mods);
    app.character_palettes = palettes->empty() ? nullptr : palettes;
    app.m->characters = app.character_palettes;
    if (app.character_palettes) LOGI("characters", "character colours from %sCharacters", mods.c_str());
    LOGI("app", "mods folder: %s", mods.c_str());
}

// What the enabled packs change in the game itself: the patch files, in the
// order they apply, and the character files with stats. Colours and the rest
// apply at once, so they are not part of it.
std::string game_signature(const App& app) {
    std::string sig;
    for (const auto& f : mod_packs::patch_files(app.packs)) sig += "patch " + f + "\n";
    for (const auto& c : load_character_mods(mod_folders(app, mod_packs::kCharacters), nullptr))
        if (!c.stats.empty()) sig += "stats " + c.path + "\n";
    return sig;
}

// A pack's preview image (mod.ini's `preview`, a PNG in its folder), loaded
// the first time the MODS page shows it; null without one.
SDL_Texture* mod_preview(App& app, const mod_packs::Pack& p, float* w, float* h) {
    if (p.loose || p.info.preview.empty() || !app.renderer) return nullptr;
    auto it = app.mod_previews.find(p.id);
    if (it == app.mod_previews.end()) {
        App::Preview pv;
        // Only a file inside the pack's own folder.
        const std::filesystem::path rel = std::filesystem::u8path(p.info.preview);
        bool inside = !rel.is_absolute() && !rel.has_root_name();
        for (const auto& part : rel) inside = inside && part != "..";
        PngImage img;
        std::string err;
        if (inside && read_png(p.dir + p.info.preview, img, &err) && img.width > 0 && img.height > 0 &&
            img.width <= 4096 && img.height <= 4096) {
            if (SDL_Surface* s = SDL_CreateSurfaceFrom(img.width, img.height, SDL_PIXELFORMAT_ARGB8888,
                                                       img.argb.data(), img.width * 4)) {
                pv.texture = SDL_CreateTextureFromSurface(app.renderer, s);
                SDL_DestroySurface(s);
                if (pv.texture) {
                    SDL_SetTextureScaleMode(pv.texture, SDL_SCALEMODE_LINEAR);
                    pv.w = float(img.width);
                    pv.h = float(img.height);
                }
            }
        } else {
            LOGW("mods", "%s: no preview from %s%s%s", p.id.c_str(), p.info.preview.c_str(), err.empty() ? "" : ": ",
                 err.c_str());
        }
        it = app.mod_previews.emplace(p.id, pv).first;
    }
    *w = it->second.w;
    *h = it->second.h;
    return it->second.texture;
}

